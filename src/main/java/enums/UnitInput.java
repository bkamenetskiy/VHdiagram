package enums;

/**
 * Перечисляет единицы измерения, доступные для ввода высоты и скорости.
 * По выбранной единице конвертер переводит высоту в метры, а скорость в м/с.
 */
public enum UnitInput {

    Meter(), Kilometer(),                                                        // длины метрические
    Foot(),                                                                      // длины имперские
    MeterPerSecond(), KilometerPerHr(), Knot()       // скорости

}


